"""H3-C analysis (run_h3c.py): instruction before the image vs after it, per model.
    python analyze_h3c.py --tag h3c_pilot200     -> analysis_h3c_pilot.md (tag in the title)
Among units whose own C0 answer states the target: violation (any mention) of T, T_first, A, A_first; paired
T_first - T and A_first - A with 95% percentile bootstrap over images (2,000, seed 0) and exact McNemar; required recall.
Two-sided; within-model comparisons only.
"""
import argparse
from collections import defaultdict
from pathlib import Path

from analyze import read_jsonl
from analyze_neu import MODELS, boot, mcnemar

HERE = Path(__file__).resolve().parent
B = lambda v: v is True or v == "True"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="h3c_pilot200")
    ap.add_argument("--out", default="analysis_h3c_pilot.md")
    args = ap.parse_args()
    out = [f"# H3-C: instruction before the image ({args.tag})", "",
           "Generated by experiments/h1_v2/analyze_h3c.py. T / A = image | question | instruction (H1); T_first / A_first =",
           "instruction | image | question. Violation = any mention, among C0-mentioned units (asr_ok). 95% CI = image bootstrap.",
           "Note: *_first moves the instruction before the image AND before the question (T_pre, not run, would separate them).", "",
           "| model | n | T | T_first | T_first - T [95% CI] | McNemar p | A | A_first | A_first - A [95% CI] | McNemar p | recall T / T_first / A / A_first |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for m in MODELS:
        p = HERE / "results" / m / f"scored_{args.tag}.jsonl"
        if not p.exists():
            out.append(f"| {m} | (missing) |"); continue
        by, img = defaultdict(dict), {}
        for r in read_jsonl(p):
            by[r["unit_id"]][r["condition"]] = r
            img[r["unit_id"]] = r["image_id"]
        U = [u for u, d in by.items() if all(B(x["asr_ok"]) for x in d.values()) and "C0" in d and B(d["C0"]["violation"])
             and all(c in d for c in ("T", "T_first", "A", "A_first"))]
        v = lambda u, c: 1.0 if B(by[u][c]["violation"]) else 0.0
        rate = lambda xs, c: sum(v(u, c) for u in xs) / len(xs)
        cells = []
        for a, b in [("T_first", "T"), ("A_first", "A")]:
            f = lambda xs, a=a, b=b: rate(xs, a) - rate(xs, b)
            lo, hi = boot(U, img, f)
            n1 = sum(v(u, a) == 1 and v(u, b) == 0 for u in U)
            n2 = sum(v(u, a) == 0 and v(u, b) == 1 for u in U)
            cells.append(f"{100 * rate(U, b):.1f} | {100 * rate(U, a):.1f} | {100 * f(U):+.1f} [{100 * lo:+.1f}, {100 * hi:+.1f}] | {mcnemar(n1, n2):.3g}")
        rec = " / ".join(f"{100 * sum(float(by[u][c]['required_recall']) for u in U) / len(U):.1f}" for c in ("T", "T_first", "A", "A_first"))
        out.append(f"| {m} | {len(U)} | {cells[0]} | {cells[1]} | {rec} |")
    (HERE / args.out).write_text("\n".join(out) + "\n")
    print(f"written {HERE / args.out}")


if __name__ == "__main__":
    main()
