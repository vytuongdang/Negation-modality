"""H3-D x H4 (CPU, Pico 2026-11-28): is the target-size effect specific to negation? On the pilot1000 H4 rows
(results/<model>/scored_pilot1000_forms.jsonl, asr_ok), units where C0 states the target. For each form (negative,
exceptive, affirmative) and channel: violation in the large-target tertile minus the small-target tertile, and the
interaction (size effect under negation - size effect under the control form) with a 95% image bootstrap CI.
Tertiles are cut on the units that have the control form (affirmative: no open existence). Same 'violation' field as
analyze.py. area_ratio from cpu_tables_b200.target_area() (target of the negative sample the form is paired with).
Observational and branch-confounded like H3-D.   python h3d_forms_b200.py -> h3d_forms_pilot1000.md"""
import json, random
from collections import defaultdict
from cpu_tables_b200 import target_area, read_jsonl, RES, MODELS, B, N_BOOT

def main():
    area = target_area(); rng = random.Random(0)
    out = ["# H3-D x H4: target-size effect by instruction form (pilot1000, asr_ok, C0-mentioned)", "",
           "Generated by experiments/h1_v2/h3d_forms_b200.py. Cells: violation % large tertile - small tertile (pp) [95% image bootstrap CI].",
           "Interaction = size effect (negative) - size effect (control form): != 0 means the size effect is specific to negation.", ""]
    for m in MODELS:
        rows = read_jsonl(RES / m / "scored_pilot1000_forms.jsonl")
        bad = {r["unit_id"] for r in rows if not B(r["asr_ok"])}
        d = defaultdict(dict); img = {}; mism = 0
        for r in rows:
            if r["unit_id"] in bad: continue
            k = r["pair_of"]; d[k][(r["form"], r["condition"])] = r; img[k] = r["image_id"]
            if r["form"] != "negative" and d[k].get(("negative", "C0")) and r["target"] != d[k][("negative", "C0")]["target"]: mism += 1
        out += [f"## {m}", ""]
        for ctrl in ("affirmative", "exceptive"):
            us = [k for k in d if ("negative", "C0") in d[k] and d[k][("negative", "C0")]["target_mentioned"]
                  and area.get(k) is not None and all((f, c) in d[k] for f in ("negative", ctrl) for c in "TAV")]
            a = sorted(area[k] for k in us); q1, q2 = a[len(a) // 3], a[2 * len(a) // 3]
            lo_t = {k for k in us if area[k] < q1}; hi_t = {k for k in us if area[k] >= q2}
            def eff(f, c):
                def g(ss):
                    s = [k for k in ss if k in hi_t]; t = [k for k in ss if k in lo_t]
                    if not s or not t: return 0.0
                    v = lambda xs: sum(B(d[k][(f, c)]["violation"]) for k in xs) / len(xs)
                    return v(s) - v(t)
                return g
            def ci(fn):
                by = defaultdict(list)
                for k in us: by[img[k]].append(k)
                ims = list(by)
                vals = sorted(fn([k for i in rng.choices(ims, k=len(ims)) for k in by[i]]) for _ in range(N_BOOT))
                return f"{100*fn(us):+.1f} [{100*vals[int(.025*N_BOOT)]:+.1f}, {100*vals[int(.975*N_BOOT)-1]:+.1f}]"
            out += [f"Control = {ctrl}: n={len(us)} units (tertile cuts {q1:.3f} / {q2:.3f}; small {len(lo_t)}, large {len(hi_t)})", "",
                    "| channel | size effect, negative | size effect, " + ctrl + " | interaction (neg - " + ctrl[:3] + ") |", "|---|---|---|---|"]
            for c in "TAV":
                inter = lambda ss, c=c: eff("negative", c)(ss) - eff(ctrl, c)(ss)
                out.append(f"| {c} | {ci(eff('negative', c))} | {ci(eff(ctrl, c))} | {ci(inter)} |")
            out.append("")
        out.append(f"(target mismatch negative vs paired form rows: {mism})\n")
    open("h3d_forms_pilot1000.md", "w").write("\n".join(out) + "\n"); print("\n".join(out))

if __name__ == "__main__":
    main()
