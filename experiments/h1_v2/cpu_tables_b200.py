"""CPU-only tables for the paper (Vy 2026-11-27), from the FULL H1 run on B200 (results/<model>/scored_all.jsonl, asr_ok
units, primary samples as in analyze.py; excluded units are not in these files):

  1. h3d_area_b200.md      H3-D: violation vs target size (area_ratio tertiles), T / A / V among C0-mentioned, plus the
                           C0 mention rate per tertile and the normalised rate P(stated | cond) / P(stated | C0).
                           area_ratio = the target component's own area_ratio (COCO / VAW / GQA, from B1), or for CLEVR
                           attribute targets bbox w*h / (image W*H). CLEVR count targets have no box -> not in H3-D.
                           B1 keeps only components whose object covers >= 3% of the image (relation objects >= 1%), so
                           the range is truncated below. Observational: size is confounded with branch / category, so
                           tertiles are also given within branch. Top - bottom tertile difference with 95% image bootstrap CI.
  2. split_by_source_b200.md  violation T / A / V by source x split group (train / val): needed before any train-vs-val claim.
  3. dataset_stats_b200_full.md  the full-set statistics table (units, images, branch x source, split, template, voice,
                           occlusion, C0 mention rate per model).
    python cpu_tables_b200.py
"""
import json
import random
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
DATA = HERE.parents[1] / "create_data" / "dataset"
MODELS = ["qwen2.5-omni-7b", "qwen2.5-omni-3b", "minicpm-o-2.6", "phi-4-mm", "internomni"]
BRANCHES = ["existence", "existence_closed", "count", "attribute", "relation"]
B = lambda v: v is True or v == "True"
N_BOOT = 2000


def read_jsonl(p):
    with open(p) as f:
        return [json.loads(l) for l in f if l.strip()]


def target_area():
    """sample_id -> area_ratio of the target component (None if unknown)."""
    out = {}
    for r in read_jsonl(DATA / "out" / "samples.jsonl"):
        t = r["negation"]["target"]
        c = next(c for c in r["components"] if c["id"] == t)
        a = c.get("area_ratio")
        if a is None and c.get("bbox"):
            m = r["extra"]["image_meta"]
            a = c["bbox"][2] * c["bbox"][3] / (m["width"] * m["height"])
        out[r["sample_id"]] = a
    return out


def load(model):
    """primary negative samples, asr_ok units: {unit: {cond: row}} (primary = non-sweep sample or N1, as analyze.py)."""
    rows = read_jsonl(RES / model / "scored_all.jsonl")
    bad = {r["unit_id"] for r in rows if not B(r["asr_ok"])}
    by = defaultdict(lambda: defaultdict(list))
    for r in rows:
        if r["unit_id"] in bad or r.get("form", "negative") != "negative":
            continue
        by[r["unit_id"]][r["condition"]].append(r)
    out = {}
    for u, d in by.items():
        pick = {}
        for c, rs in d.items():
            rs = [x for x in rs if not B(x.get("template_sweep"))] or [x for x in rs if x.get("template_id") == "N1"] or rs
            pick[c] = rs[0]
        out[u] = pick
    return out


def boot_diff(units, img, f, rng):
    by = defaultdict(list)
    for u in units:
        by[img[u]].append(u)
    ims = list(by)
    vals = sorted(f([u for i in rng.choices(ims, k=len(ims)) for u in by[i]]) for _ in range(N_BOOT))
    return vals[int(0.025 * N_BOOT)], vals[int(0.975 * N_BOOT) - 1]


def pct(x):
    return "-" if x is None else f"{100 * x:.1f}"


def rate(xs):
    xs = list(xs)
    return sum(xs) / len(xs) if xs else None


def h3d(models, area):
    out = ["# H3-D: violation vs target size (area_ratio tertiles), full H1 set, asr_ok", "",
           "Generated by experiments/h1_v2/cpu_tables_b200.py. Violation = any mention, among C0-mentioned units.",
           "norm = P(target stated | condition) / P(target stated | C0), on ALL units of the tertile (not only C0-mentioned).",
           "Size filter in B1: every component object >= 3% of the image (relation object >= 1%), so small targets are absent.",
           "Observational: size is confounded with branch and category (see the within-branch table). CLEVR count targets",
           "have no box and are left out.", ""]
    for m in models:
        d = load(m)
        units = [u for u in d if "C0" in d[u] and area.get(d[u]["C0"]["sample_id"]) is not None]
        a = {u: area[d[u]["C0"]["sample_id"]] for u in units}
        img = {u: d[u]["C0"]["image_id"] for u in units}
        cuts = sorted(a.values())
        q1, q2 = cuts[len(cuts) // 3], cuts[2 * len(cuts) // 3]
        tert = {u: 0 if a[u] < q1 else (1 if a[u] < q2 else 2) for u in units}
        out += [f"## {m}", "", f"{len(units)} units with a target area; tertile cuts {q1:.3f} / {q2:.3f} (area share of the image).", "",
                "| tertile | n | C0 states % | viol T | viol A | viol V | norm T | norm A | norm V |", "|---|---|---|---|---|---|---|---|---|"]
        for t, name in enumerate(["small", "medium", "large"]):
            us = [u for u in units if tert[u] == t]
            c0m = [u for u in us if B(d[u]["C0"]["violation"])]
            c0r = rate(B(d[u]["C0"]["violation"]) for u in us)
            cells = [pct(rate(B(d[u][c]["violation"]) for u in c0m if c in d[u])) for c in "TAV"]
            norms = [f"{rate(B(d[u][c]['violation']) for u in us if c in d[u]) / c0r:.2f}" if c0r else "-" for c in "TAV"]
            out.append(f"| {name} | {len(us)} | {pct(c0r)} | " + " | ".join(cells) + " | " + " | ".join(norms) + " |")
        rng = random.Random(0)
        c0m = [u for u in units if B(d[u]["C0"]["violation"]) and tert[u] != 1]
        cells = []
        for c in "TAV":
            us = [u for u in c0m if c in d[u]]
            f = lambda xs, c=c: (rate(B(d[u][c]["violation"]) for u in xs if tert[u] == 2) or 0) - \
                (rate(B(d[u][c]["violation"]) for u in xs if tert[u] == 0) or 0)
            lo, hi = boot_diff(us, img, f, rng)
            cells.append(f"{100 * f(us):+.1f} [{100 * lo:+.1f}, {100 * hi:+.1f}]")
        out += ["", "large - small tertile, violation (pp) [95% image bootstrap CI]: T " + cells[0] + "; A " + cells[1] + "; V " + cells[2], ""]
        out += ["Within branch (violation T / A / V among C0-mentioned; tertiles cut within the branch):", "",
                "| branch | small | medium | large |", "|---|---|---|---|"]
        for b in BRANCHES:
            ub = [u for u in units if d[u]["C0"]["branch"] == b]
            if len(ub) < 30:
                continue
            cs = sorted(a[u] for u in ub)
            c1, c2 = cs[len(cs) // 3], cs[2 * len(cs) // 3]
            row = []
            for t in range(3):
                us = [u for u in ub if (0 if a[u] < c1 else (1 if a[u] < c2 else 2)) == t and B(d[u]["C0"]["violation"])]
                row.append(" / ".join(pct(rate(B(d[u][c]["violation"]) for u in us if c in d[u])) for c in "TAV") + f" (n={len(us)})")
            out.append(f"| {b} | " + " | ".join(row) + " |")
        out.append("")
    (HERE / "h3d_area_b200.md").write_text("\n".join(out) + "\n")


def split_by_source(models):
    out = ["# Violation by source x split (full H1 set, asr_ok, among C0-mentioned; T / A / V %)", "",
           "Generated by experiments/h1_v2/cpu_tables_b200.py. Split group as in analyze.py (val = val/test images).",
           "Read train-vs-val WITHIN a source only: the sources differ in branch mix and difficulty.", ""]
    for m in models:
        d = load(m)
        cell = defaultdict(list)
        for u, x in d.items():
            if "C0" in x and B(x["C0"]["violation"]):
                cell[(x["C0"]["source"], x["C0"]["split_group"])].append(u)
        out += [f"## {m}", "", "| source | train: n, T / A / V | val: n, T / A / V |", "|---|---|---|"]
        for src in sorted({k[0] for k in cell}):
            row = []
            for sg in ["train", "val"]:
                us = cell.get((src, sg), [])
                row.append(f"n={len(us)}, " + " / ".join(pct(rate(B(d[u][c]["violation"]) for u in us if c in d[u])) for c in "TAV")
                           if us else "-")
            out.append(f"| {src} | {row[0]} | {row[1]} |")
        out.append("")
    (HERE / "split_by_source_b200.md").write_text("\n".join(out) + "\n")


def stats(models):
    d = load(MODELS[0])
    c0 = [x["C0"] for x in d.values() if "C0" in x]
    out = ["# Dataset v2, full set on B200: statistics (H1 units, asr_ok)", "",
           "Generated by experiments/h1_v2/cpu_tables_b200.py from results/<model>/scored_all.jsonl (C0 rows).", "",
           f"Units (questions): {len(c0)}; images: {len({r['image_id'] for r in c0})}.", "",
           "| branch | " + " | ".join(sorted({r['source'] for r in c0})) + " | total |", "|---|" + "---|" * (len({r['source'] for r in c0}) + 1)]
    srcs = sorted({r["source"] for r in c0})
    for b in BRANCHES:
        n = Counter(r["source"] for r in c0 if r["branch"] == b)
        out.append(f"| {b} | " + " | ".join(str(n.get(s, 0)) for s in srcs) + f" | {sum(n.values())} |")
    n = Counter(r["source"] for r in c0)
    out.append("| total | " + " | ".join(str(n[s]) for s in srcs) + f" | {len(c0)} |")
    for f in ["split_group", "split", "template_id", "voice", "occludes_subject", "template_sweep"]:
        out.append(f"\n- {f}: " + ", ".join(f"{k} {v}" for k, v in sorted(Counter(str(r[f]) for r in c0).items())))
    out += ["", "C0 states the target (no instruction), per model:", "", "| model | n | C0 states % |", "|---|---|---|"]
    for m in models:
        dm = load(m)
        xs = [B(x["C0"]["violation"]) for x in dm.values() if "C0" in x]
        out.append(f"| {m} | {len(xs)} | {pct(rate(xs))} |")
    (HERE / "dataset_stats_b200_full.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    area = target_area()
    h3d(MODELS, area)
    split_by_source(MODELS)
    stats(MODELS)
    print("written h3d_area_b200.md, split_by_source_b200.md, dataset_stats_b200_full.md")
