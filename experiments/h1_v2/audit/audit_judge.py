"""B200 draft audit (CPU, read-only on results): judge reliability per model x run.
Counts judge_source (fast / think / think_error), regex-vs-judge disagreement on the target, and writes
the union of unit_ids that have any think_error row (per run tag) as a removal list for analyze.py --remove.
    python audit/audit_judge.py   -> audit/judge_audit.md, audit/rm_think_error_<tag>.txt
"""
import json, collections
from pathlib import Path
HERE = Path(__file__).resolve().parent
RES = HERE.parent / "results"
MODELS = ["qwen2.5-omni-7b", "qwen2.5-omni-3b", "minicpm-o-2.6", "phi-4-mm", "internomni"]
TAGS = ["all", "pilot1000_forms", "pilot1000_C0_box-OCR_V", "h2_pilot1000"]
B = lambda v: str(v) == "True"
out = ["# Judge audit (B200, generated by audit/audit_judge.py)", "",
       "think_error = the thinking judge gave no JSON; the row keeps the fast-judge verdict.",
       "disagree = judge target_mentioned != regex_target_mentioned (all rows, all conditions).", "",
       "| run | model | rows | fast | think | think_error | think_error % | judge!=regex | units w/ think_error |",
       "|---|---|---|---|---|---|---|---|---|"]
for tag in TAGS:
    union = set()
    for m in MODELS:
        p = RES / m / f"scored_{tag}.jsonl"
        if not p.exists():
            out.append(f"| {tag} | {m} | (missing) | | | | | | |"); continue
        c = collections.Counter(); dis = 0; n = 0; units = set()
        for l in open(p):
            r = json.loads(l); n += 1
            c[r.get("judge_source")] += 1
            if B(r.get("target_mentioned")) != B(r.get("regex_target_mentioned")):
                dis += 1
            if r.get("judge_source") == "think_error":
                units.add(r["unit_id"])
        union |= units
        out.append(f"| {tag} | {m} | {n} | {c['fast']} | {c['think']} | {c['think_error']} | "
                   f"{100*c['think_error']/n:.2f} | {dis} ({100*dis/n:.1f}%) | {len(units)} |")
    (HERE / f"rm_think_error_{tag}.txt").write_text("# units with a think_error row in any model\n" + "\n".join(sorted(union)) + "\n")
    out.append(f"| {tag} | UNION | | | | | | | {len(union)} |")
(HERE / "judge_audit.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
